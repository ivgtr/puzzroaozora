function scene(
  id: string, work: keyof typeof works, premise: string, marked: string,
  normalGroups: readonly (readonly number[])[], speechReadings: readonly string[],
  location: string, hints: readonly string[], note: string,
): CuratedPassage {
  const original = marked.replaceAll("|", "");
  const hardFragments = comparisonText(marked).split("|");
  const fragments = normalGroups.map((group) => group.map((index) => hardFragments[index]).join(""));
  return { id, ...works[work], curatedVersion: 1, difficulty: "normal", sceneTitle: works[work].title, premise, original, fragments, hardFragments, speechReadings, location, hints, note };
}

